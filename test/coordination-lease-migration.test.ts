function legacyV3(f: ReturnType<typeof executionFixture>, path: string) {
  historicalDatabase(f, path, 2);
  const raw = new DatabaseSync(path);
  raw.exec(MIGRATIONS[2].sql);
  raw.prepare('INSERT INTO schema_migrations VALUES (3,?,?)').run(MIGRATIONS[2].id, 1);
  raw.exec('PRAGMA user_version=3');
  // A real 5C-1 transition, generated by the unmodified 003 triggers.
  raw.exec("UPDATE execution_ledger SET state='DISPATCH_RESERVED',attempt_id='legacy-attempt',reserved_at=10,updated_at=10 WHERE action_id='action'");
  return raw;
}
const all = (raw: DatabaseSync) => Object.fromEntries(['workflow_seeds','journal_events','workflow_checkpoints','pending_actions','execution_ledger','execution_results','runner_evidence','runtime_audit_events'].map(table => [table, raw.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all()]));
for (const version of [0,1,2,3] as const) test(`Migration ${version}→4 preserves artifacts and history and never grants a lease to RUNNING work`, t => {
  const f = executionFixture(t); f.register(); f.store.createCheckpoint('run');
  const path = join(f.dir, `v${version}.sqlite`);
  let raw: DatabaseSync;
  if (version === 3) raw = legacyV3(f, path);
  else { if (version) historicalDatabase(f, path, version); raw = new DatabaseSync(path); }
  t.after(() => raw.close());
  const tables = version === 0 ? [] : ['workflow_seeds','journal_events','workflow_checkpoints',
    ...(version >= 2 ? ['pending_actions','execution_ledger','execution_results','runner_evidence'] : []),
    ...(version >= 3 ? ['runtime_audit_events'] : [])];
  const before = Object.fromEntries(tables.map(table => [table, raw.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all()]));
  const db = new DurableDatabase({ path });
  try {
    assert.equal(raw.prepare('PRAGMA user_version').get()!.user_version, 4);
    assert.deepEqual(raw.prepare('SELECT migration_id FROM schema_migrations ORDER BY schema_version').all().map(row => row.migration_id), MIGRATIONS.map(m => m.id));
    for (const [table, rows] of Object.entries(before)) assert.deepEqual(raw.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all(), rows);
    assert.equal(raw.prepare('SELECT count(*) AS n FROM runtime_leases').get()!.n, 0);
    if (version) {
      assert.equal(new SqliteCoordinationRunnerStore(db).getSnapshot('run').run.status, 'RUNNING');
      const inspection = new RecoveryReader(db, clock).inspect('run'); assert.equal(inspection.executable, false); assert.equal(inspection.executionAllowed, false);
      assert.notEqual(inspection.disposition, 'RECOVERY_FAILED');
      assert.throws(() => new SqliteCoordinationRunnerStore(db).append(usage(f.snapshot())), { code: 'LEASE_FENCED' });
    }
  } finally { db.close(); }
  const again = new DurableDatabase({ path }); again.close();
  assert.equal(raw.prepare('SELECT count(*) AS n FROM schema_migrations').get()!.n, 4);
});
test('Immutable migration boundary distinguishes genuine NULL Runtime 5C-1 audit from fenced 5C-2 changes', t => {
  const f = executionFixture(t); f.register(); const path = join(f.dir, 'legacy.sqlite'), raw = legacyV3(f, path); t.after(() => raw.close());
  const before = all(raw), legacy = before.runtime_audit_events;
  assert.ok(legacy.length); assert.ok(legacy.every(row => row.runtime_instance_id === null && row.runtime_generation === null));
  const db = new DurableDatabase({ path }); t.after(() => db.close());
  assert.deepEqual(all(raw), before);
  assert.equal(raw.prepare('SELECT legacy_audit_sequence AS n FROM runtime_fencing_boundary').get()!.n, legacy.at(-1)!.audit_sequence);
  const manager = createRuntimeLeaseManager(db), lease = manager.acquire('run'), store = new SqliteCoordinationRunnerStore(db, lease);
  store.append({ ...usage(store.getSnapshot('run')), timestamp: 10 });
  const reader = new RecoveryReader(db, clock); assert.notEqual(reader.inspect('run').disposition, 'RECOVERY_FAILED');
  const timeline = reader.getWorkflowTimeline('run').entries;
  assert.ok(timeline.some(e => e.eventKind === 'EXECUTION_CHANGED' && e.runtimeInstanceId === undefined));
  assert.ok(timeline.some(e => e.eventKind === 'UsageRecorded' && e.runtimeInstanceId === lease.runtimeInstanceId && e.generation === 1));
  assert.equal(raw.prepare('SELECT schema_version FROM execution_ledger').get()!.schema_version, 1);
  // Reader must reject removal of verified metadata even when the immutable trigger is deliberately bypassed.
  raw.exec('DROP TRIGGER audit_no_update');
  raw.exec("UPDATE runtime_audit_events SET runtime_instance_id=NULL,runtime_generation=NULL WHERE event_kind='JOURNAL_APPENDED'");
  assert.equal(reader.inspect('run').disposition, 'RECOVERY_FAILED');
});
test('Migration 004 failure rolls back all DDL, boundary, ledger and user_version', t => {
  const f = executionFixture(t); f.register(); const path = join(f.dir, 'rollback.sqlite'), raw = legacyV3(f, path); t.after(() => raw.close());
  const before = all(raw), exec = DatabaseSync.prototype.exec;
  DatabaseSync.prototype.exec = function(sql: string) { exec.call(this, sql); if (sql.includes('CREATE TABLE runtime_leases')) throw Error('private'); };
  try { assert.throws(() => new DurableDatabase({ path }), { code: 'DATABASE_ERROR' }); }
  finally { DatabaseSync.prototype.exec = exec; }
  assert.equal(raw.prepare('PRAGMA user_version').get()!.user_version, 3);
  assert.equal(raw.prepare('SELECT count(*) AS n FROM schema_migrations').get()!.n, 3);
  assert.equal(raw.prepare("SELECT count(*) AS n FROM sqlite_master WHERE name IN ('runtime_leases','runtime_fencing_boundary')").get()!.n, 0);
  assert.deepEqual(all(raw), before);
  const db = new DurableDatabase({ path }); db.close(); assert.deepEqual(all(raw), before);
});
for (const boundary of ['before-ddl','after-ddl','after-commit']) test(`${terminationName} Migration 004/${boundary} preserves a complete old or new schema`, async t => {
  const f = executionFixture(t); f.register(); const path = join(f.dir, `${boundary}.sqlite`), raw = legacyV3(f, path); t.after(() => raw.close());
  const before = all(raw);
  const child = fork(fileURLToPath(new URL('./lease-migration-child.ts', import.meta.url)), [path, boundary], {
    execArgv: ['--experimental-transform-types','--loader',fileURLToPath(new URL('./ts-loader.mjs', import.meta.url))], stdio: ['ignore','ignore','ignore','ipc'],
  });
  const closed = new Promise<void>(resolve => child.once('exit', () => resolve()));
  let timer: ReturnType<typeof setTimeout>;
  const stage = new Promise<any>((resolve, reject) => { timer = setTimeout(() => reject(Error('Migration child timeout')), 10_000); child.once('message', resolve); child.once('error', reject); child.once('exit', () => reject(Error('Migration child exited'))); });
  t.after(async () => { clearTimeout(timer); if (child.exitCode === null && child.signalCode === null) terminateChild(child); await closed; });
  assert.deepEqual(await stage, { stage: boundary }); clearTimeout(timer); terminateChild(child); await closed;
  const version = boundary === 'after-commit' ? 4 : 3;
  assert.equal(raw.prepare('PRAGMA user_version').get()!.user_version, version);
  assert.equal(raw.prepare('SELECT count(*) AS n FROM schema_migrations').get()!.n, version);
  assert.equal(raw.prepare("SELECT count(*) AS n FROM sqlite_master WHERE name='runtime_fencing_boundary'").get()!.n, version === 4 ? 1 : 0);
  assert.deepEqual(all(raw), before);
  const db = new DurableDatabase({ path }); try { assert.notEqual(new RecoveryReader(db, clock).inspect('run').disposition, 'RECOVERY_FAILED'); } finally { db.close(); }
});
